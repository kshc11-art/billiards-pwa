/** 카테고리별 기술 ID 조회. */
export function getTechniquesByCategory(category: TechniqueCategory): TechniqueId[] {
  return Object.values(TECHNIQUE_CONTENT)
    .filter((t) => t.category === category)
    .sort((a, b) => b.difficulty - a.difficulty)
    .map((t) => t.id);
}

/** 기술 ID로 콘텐츠 조회. */
export function getTechniqueContent(id: TechniqueId): TechniqueContent {
  return TECHNIQUE_CONTENT[id];
}

/** 우선순위(난이도) 별 기술 조회. */
export function getTechniquesByDifficulty(difficulty: 1 | 2 | 3 | 4 | 5): TechniqueId[] {
  return Object.values(TECHNIQUE_CONTENT)
    .filter((t) => t.difficulty === difficulty)
    .map((t) => t.id);
}
