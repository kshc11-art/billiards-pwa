// 기술 ID
export type TechniqueId =
  // 샷 종류 11종
  | 'back-spin' // 뒤돌리기 (우라마와시)
  | 'side-spin' // 옆돌리기 (제각/하꾸)
  | 'front-spin' // 앞돌리기 (오마)
  | 'cut-shot' // 비껴치기 (걸어치기/힛카케)
  | 'vertical' // 세워치기
  | 'bank' // 빈쿠션 (3뱅크/넣어치기)
  | 'double-rail' // 더블레일 (조단조/접시)
  | 'double-cushion' // 더블쿠션 (안더블/뒷더블)
  | 'crossing' // 횡단샷
  | 'long-angle' // 대회전
  | 'kobayashi' // 고바야시 더블
  // 스트로크 기술 6종
  | 'push' // 밀어치기 (오시)
  | 'draw' // 끌어치기 (히키)
  | 'short-stroke' // 끊어치기
  | 'jab-stroke' // 잡아치기 (잽 샷)
  | 'masse' // 마세 (찍어치기)
  | 'curve'; // 곡구

export type TechniqueCategory = 'shot' | 'stroke';

export interface TechniqueContent {
  id: TechniqueId;
  category: TechniqueCategory;
  name: { ko: string; en: string };
  alternateNames?: string[];
  /** 1-5 ★ 우선순위. */
  difficulty: 1 | 2 | 3 | 4 | 5;

  /** 기술 정의 — 한 줄. */
  definition: string;
  /** 정의 부연 설명. */
  detail?: string;

  /** 기본 자세·큐대 사용. */
  posture?: string;

  /** 표준값. */
  standard: {
    impact: string; // 당점 (예: 12시 무회전 / 9:30 3팁)
    thickness: string; // 두께 (예: 1/2, 6/8, 자유)
    speed: string; // 속도 (예: 2-3 레일)
    stroke: string; // 스트로크 (예: 평범, 끊어, 밀어, 잽)
  };

  /** 핵심 포인트. */
  keyPoints: string[];

  /** 흔한 실수. */
  commonMistakes: string[];

  /** 응용 케이스. */
  applications?: { situation: string; description: string }[];

  /**
   * 영상·강좌 표준 예제 (japong·당구박사·필승당구 형식).
   * InfoBox에 표시되는 핵심 학습 데이터.
   * 각 예제는 "당점/두께/스트로크" 3요소 필수.
   */
  examples?: {
    /** 배치 코드 (japong 형식): 수구위치_1적구위치_2적구위치 (예: 5830_6808_4733). */
    layout?: string;
    /** 강좌·영상 출처 (예: '당구박사 3번', '재퐁', '이충복 레슨'). */
    source: string;
    /** 배치 특징 (예: '키스 위험', '세이프티 포지션', '얇은 두께 필요'). */
    feature?: string;
    /** 당점 — 시계 방향 + 팁수 (예: '2시 방향 3팁', '12시 2팁'). */
    impact: string;
    /** 두께 — japong 표준 (예: '제1적구의 왼쪽 1/2', '오른쪽 4/5'). */
    thickness: string;
    /** 스트로크 — japong 표준 (예: '강하게 밀어치기', '부드럽게 밀어치기', '짧고 빠르게'). */
    stroke: string;
    /** 추가 메모 (선택, 키스 회피·포지션 등). */
    note?: string;
  }[];

  /** 출처. */
  sources: string[];
}

